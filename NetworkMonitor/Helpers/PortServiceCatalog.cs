    public static string Lookup(string protocol, int port)
    {
        if (port <= 0) return string.Empty;
        var dict = string.Equals(protocol, "UDP", System.StringComparison.OrdinalIgnoreCase) ? Udp : Tcp;
        return dict.TryGetValue(port, out var name) ? name : string.Empty;
    }

    public static string LookupPair(string protocol, int localPort, int remotePort)
    {
        var remote = Lookup(protocol, remotePort);
        var local = Lookup(protocol, localPort);
        if (!string.IsNullOrEmpty(remote)) return remote;
        if (!string.IsNullOrEmpty(local)) return local;
        return string.Empty;
    }
